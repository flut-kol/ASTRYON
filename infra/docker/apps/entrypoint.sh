#!/bin/sh
# DEV ONLY. Runs the 11-service set in one container. Default: static dev token read from
# /run/secrets/astryon-dev-token (never logged). Opt-in AAS mode: set AAS_BASE_URL (+ AAS_ISSUER, AAS_AUDIENCE,
# AAS_ALLOWED_AZP, AAS_ENV). Exits (and Docker restarts the container) as soon as any process dies or on SIGTERM.
set -u
TENANT="${TENANT:-00000000-0000-0000-0000-0000000000a1}"
TOKEN=""
if [ -z "${AAS_BASE_URL:-}" ]; then
  TOKEN="$(cat /run/secrets/astryon-dev-token 2>/dev/null)" || { echo "dev token file /run/secrets/astryon-dev-token is missing or unreadable" >&2; exit 2; }
  [ -n "$TOKEN" ] || { echo "dev token file is empty" >&2; exit 2; }
fi
KAFKA=kafka:9092; CH_URL=http://clickhouse:8123; PG="postgres://demo_app:demo_dev_only@postgres:5432/astryon"
S3ENV="FILE_S3_ENDPOINT=http://s3mock:9090 FILE_S3_BUCKET=files FILE_S3_REGION=us-east-1 FILE_S3_ACCESS_KEY=demo FILE_S3_SECRET_KEY=demo-dev-only"
CHENV="CH_URL=$CH_URL CH_DATABASE=astryon CH_USER=astryon CH_PASSWORD=astryon_dev_only"
AASV="AAS_BASE_URL=${AAS_BASE_URL:-} AAS_ISSUER=${AAS_ISSUER:-} AAS_AUDIENCE=${AAS_AUDIENCE:-} AAS_ENV=${AAS_ENV:-prod} AAS_ALLOWED_AZP=${AAS_ALLOWED_AZP:-}"
if [ -n "$AAS_BASE_URL" ]; then
  FAUTH="$AASV"; GWAUTH="$AASV"; QAUTH="$AASV"; RCAUTH="$AASV"; EXAUTH="$AASV"; QUAUTH="$AASV"; CMAUTH="ASTRYON_AAS_BASE_URL=$AAS_BASE_URL ASTRYON_AAS_ISSUER=$AAS_ISSUER ASTRYON_AAS_AUDIENCE=$AAS_AUDIENCE ASTRYON_AAS_ENV=${AAS_ENV:-prod} ASTRYON_AAS_ALLOWED_AZP=$AAS_ALLOWED_AZP"
else
  FAUTH="FILE_API_DEV_TOKEN=$TOKEN FILE_API_DEV_TENANT=$TENANT"; GWAUTH="ASTRYON_DEV_AUTH=1 ASTRYON_DEV_TOKEN=$TOKEN ASTRYON_DEV_TENANT_ID=$TENANT"; QAUTH="QUERY_DEV_TOKEN=$TOKEN QUERY_DEV_TENANT=$TENANT"
  RCAUTH="REPLAY_DEV_TOKEN=$TOKEN REPLAY_DEV_TENANT_ID=$TENANT"; EXAUTH="EXPORT_DEV_TOKEN=$TOKEN EXPORT_DEV_TENANT=$TENANT"
  QUAUTH="QUARANTINE_ENABLE_DEV_AUTH=true QUARANTINE_DEV_TOKEN=$TOKEN QUARANTINE_DEV_TENANT=$TENANT"; CMAUTH="ASTRYON_CONNECTOR_DEV_TOKEN=$TOKEN ASTRYON_CONNECTOR_DEV_TENANT=$TENANT"
fi
run() { n=$1; shift; env "$@" /app/$n 2>&1 | sed "s/^/[$n] /" & }
run gateway ASTRYON_GATEWAY_ADDR=:18080 $GWAUTH ASTRYON_KAFKA_BROKERS=$KAFKA
run clickhouse-sink CHSINK_KAFKA_BROKERS=$KAFKA CHSINK_TOPIC=raw.events.v1 CHSINK_GROUP_ID=demo-sink CHSINK_CH_URL=$CH_URL CHSINK_CH_USER=astryon CHSINK_CH_PASSWORD=astryon_dev_only
run file-api LISTEN_ADDR=:18085 $FAUTH FILE_API_PG_URL=$PG FILE_ARCHIVE_MODE=${FILE_ARCHIVE_MODE:-} $S3ENV
run file-worker FILE_WORKER_PG_URL=$PG $S3ENV $CHENV FILE_EVENT_TYPE=file.row FILE_CREDENTIALS_POLICY=quarantine \
  FILE_SCANNER_MODE=${FILE_SCANNER_MODE:-off} FILE_SCANNER_DEFENDER_URL=${FILE_SCANNER_DEFENDER_URL:-} \
  FILE_SCANNER_CLAMAV_URL=${FILE_SCANNER_CLAMAV_URL:-} FILE_SCANNER_STAGE_DIR=${FILE_SCANNER_STAGE_DIR:-} \
  FILE_SCANNER_MAX_STAGE_BYTES=${FILE_SCANNER_MAX_STAGE_BYTES:-} FILE_SCANNER_TIMEOUT=${FILE_SCANNER_TIMEOUT:-}
run query-api LISTEN_ADDR=:18082 $QAUTH $CHENV QUERY_PG_URL=$PG
run replay-controller REPLAY_ADDR=:18087 $RCAUTH "REPLAY_DEV_SCOPES=astryon:replay:write astryon:replay:read" REPLAY_PG_URL=$PG $CHENV ASTRYON_KAFKA_BROKERS=$KAFKA
run replay-worker ASTRYON_KAFKA_BROKERS=$KAFKA REPLAYW_PG_URL=$PG REPLAYW_CH_URL=$CH_URL REPLAYW_CH_DATABASE=astryon REPLAYW_CH_USER=astryon REPLAYW_CH_PASSWORD=astryon_dev_only
run export-worker LISTEN_ADDR=:18083 $EXAUTH EXPORT_PG_URL=$PG $CHENV S3_ENDPOINT=http://s3mock:9090 S3_BUCKET=exports S3_REGION=us-east-1 S3_ACCESS_KEY=demo S3_SECRET_KEY=demo-dev-only
run quarantine LISTEN_ADDR=:18086 $QUAUTH $CHENV ASTRYON_KAFKA_BROKERS=$KAFKA
run connector-manager ASTRYON_CONNECTOR_ADMIN_ADDR=:18088 $CMAUTH ASTRYON_DATABASE_URL=$PG CONNPULL_PG_URL=$PG ASTRYON_KAFKA_BROKERS=$KAFKA ASTRYON_CONNECTOR_METRICS_ADDR=:18089
run retry-controller DATABASE_URL=$PG ASTRYON_RETRY_METRICS_ADDR=:18081
trap 'kill 0; exit 0' TERM INT
wait -n; echo "a service exited; stopping"; kill 0; exit 1
